    private void btnTestarWebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTestarWebActionPerformed
        // TODO add your handling code here:
        String urlStr = txtLinkEncurtado.getText();

            if (!urlStr.isEmpty()) {
                try {
                    // Adiciona "https://" caso o usuário digite apenas o domínio (ex: google.com)
                    if (!urlStr.startsWith("http://") && !urlStr.startsWith("https://")) {
                        urlStr = "https://" + urlStr;
                    }

                    URI uri = new URI(urlStr);
                    Desktop.getDesktop().browse(uri);
                } catch (Exception ex) {
                    ex.printStackTrace();
                    // Opcional: exiba um JOptionPane.showMessageDialog informando que o link é inválido
                }
            }
        
    }//GEN-LAST:event_btnTestarWebActionPerformed

